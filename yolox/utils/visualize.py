import cv2
import numpy as np

__all__ = ["vis", "vis_polygon"]


def vis(img, boxes, scores, cls_ids, conf=0.5, class_names=None):

    for i in range(len(boxes)):
        box = boxes[i]
        cls_id = int(cls_ids[i])
        score = scores[i]
        if score < conf:
            continue
        x0 = int(box[0])
        y0 = int(box[1])
        x1 = int(box[2])
        y1 = int(box[3])

        color = (_COLORS[cls_id] * 255).astype(np.uint8).tolist()
        text = '{}:{:.1f}%'.format(class_names[cls_id], score * 100)
        txt_color = (0, 0, 0) if np.mean(_COLORS[cls_id]) > 0.5 else (255, 255, 255)
        font = cv2.FONT_HERSHEY_SIMPLEX

        txt_size = cv2.getTextSize(text, font, 0.4, 1)[0]
        cv2.rectangle(img, (x0, y0), (x1, y1), color, 2)

        txt_bk_color = (_COLORS[cls_id] * 255 * 0.7).astype(np.uint8).tolist()
        cv2.rectangle(
            img,
            (x0, y0 + 1),
            (x0 + txt_size[0] + 1, y0 + int(1.5*txt_size[1])),
            txt_bk_color,
            -1
        )
        cv2.putText(img, text, (x0, y0 + txt_size[1]), font, 0.4, txt_color, thickness=1)

    return img


def vis_polygon(img, polygons, scores, cls_ids, conf=0.5, class_names=None):
    """
    Visualize polygon bounding boxes on image.
    
    Args:
        img: Input image (numpy array)
        polygons: List of polygons, each with 8 values (x1,y1, x2,y2, x3,y3, x4,y4)
        scores: List of confidence scores
        cls_ids: List of class IDs
        conf: Confidence threshold
        class_names: List of class names
    
    Returns:
        Image with drawn polygons.
    """
    for i in range(len(polygons)):
        poly = polygons[i]
        cls_id = int(cls_ids[i])
        score = scores[i]
        if score < conf:
            continue
        
        # Extract 4 corner points
        pts = np.array([
            [int(poly[0]), int(poly[1])],
            [int(poly[2]), int(poly[3])],
            [int(poly[4]), int(poly[5])],
            [int(poly[6]), int(poly[7])]
        ], np.int32).reshape((-1, 1, 2))
        
        color = (_COLORS[cls_id % len(_COLORS)] * 255).astype(np.uint8).tolist()
        txt_color = (0, 0, 0) if np.mean(_COLORS[cls_id % len(_COLORS)]) > 0.5 else (255, 255, 255)
        font = cv2.FONT_HERSHEY_SIMPLEX
        
        # Draw polygon outline
        cv2.polylines(img, [pts], True, color, 2)
        
        # Draw corner points
        for j in range(4):
            cv2.circle(img, (int(poly[j*2]), int(poly[j*2+1])), 3, color, -1)
        
        # Draw label at first corner
        if class_names is not None:
            text = '{}:{:.1f}%'.format(class_names[cls_id], score * 100)
            txt_size = cv2.getTextSize(text, font, 0.4, 1)[0]
            
            x0, y0 = int(poly[0]), int(poly[1])
            txt_bk_color = (_COLORS[cls_id % len(_COLORS)] * 255 * 0.7).astype(np.uint8).tolist()
            cv2.rectangle(
                img,
                (x0, y0 - txt_size[1] - 4),
                (x0 + txt_size[0] + 1, y0),
                txt_bk_color,
                -1
            )
            cv2.putText(img, text, (x0, y0 - 2), font, 0.4, txt_color, thickness=1)

    return img


